# ─── Archive realm ────────────────────────────────────────────────────────────

class TestArchiveRealm:
    """DELETE /api/realms/:realmId"""

    def test_project_admin_can_archive_a_fresh_realm(
        self, admin_session: requests.Session
    ) -> None:
        """Create a throwaway realm and then archive it."""
        payload = _realm_payload()
        create_resp = admin_session.post(f"{API}/realms", json=payload, timeout=15)
        assert create_resp.status_code == 201
        new_realm_id = create_resp.json()["data"]["realm"]["id"]

        delete_resp = admin_session.delete(
            f"{API}/realms/{new_realm_id}", timeout=10
        )
        assert delete_resp.status_code in (200, 204)

    def test_student_cannot_archive_realm(self, student_session: requests.Session) -> None:
        resp = student_session.delete(f"{API}/realms/{SEEDED_REALM_ID}", timeout=10)
        assert resp.status_code in (403, 401)
